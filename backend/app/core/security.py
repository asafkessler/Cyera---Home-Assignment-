"""
Security primitives: password hashing, random secrets, secret hashing, and
encryption of stored credentials. Nothing here knows about HTTP or the DB.

Two different hashing strategies on purpose:

- Passwords are low-entropy (people choose them), so they get bcrypt, which is
  deliberately slow to make brute force expensive.
- Session tokens and API keys are generated by us with 256 bits of randomness,
  so a plain SHA-256 is enough: brute-forcing the input space is infeasible,
  and a fast hash keeps every request cheap.
"""
import hashlib
import secrets

import bcrypt
from cryptography.fernet import Fernet, InvalidToken


# --- Passwords ---------------------------------------------------------------

def hash_password(password: str) -> str:
    return bcrypt.hashpw(password.encode("utf-8"), bcrypt.gensalt()).decode("utf-8")


def verify_password(password: str, password_hash: str) -> bool:
    return bcrypt.checkpw(password.encode("utf-8"), password_hash.encode("utf-8"))


# --- Random secrets (session tokens, API keys) ------------------------------

def generate_secret(nbytes: int = 32) -> str:
    """URL-safe random string with `nbytes` of entropy (32 bytes = 256 bits)."""
    return secrets.token_urlsafe(nbytes)


def hash_secret(secret: str) -> str:
    """Stable hash for looking up a stored secret without storing the secret."""
    return hashlib.sha256(secret.encode("utf-8")).hexdigest()


# --- Encryption at rest (Jira API tokens) -----------------------------------

class CredentialCipher:
    """
    Authenticated symmetric encryption (Fernet: AES-128-CBC + HMAC-SHA256).

    The key comes from APP_ENCRYPTION_KEY. Without it, a copy of the database
    file alone does not reveal any Jira token.
    """

    def __init__(self, key: str):
        self._fernet = Fernet(key.encode("utf-8"))

    def encrypt(self, plaintext: str) -> str:
        return self._fernet.encrypt(plaintext.encode("utf-8")).decode("utf-8")

    def decrypt(self, ciphertext: str) -> str:
        try:
            return self._fernet.decrypt(ciphertext.encode("utf-8")).decode("utf-8")
        except InvalidToken as exc:
            # Wrong key or tampered data. Treat as unrecoverable; callers
            # should ask the user to reconnect Jira.
            raise ValueError("Stored credential cannot be decrypted with the current key") from exc
